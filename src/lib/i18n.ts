export function reasonText(reason: { key: string; params: Record<string, string | number> }, lang: Lang): string {
  const entry = REASONS[reason.key as ReasonKey];
  if (!entry) return reason.key;
  const params: Record<string, string | number> = { ...reason.params };
  if (typeof params.amount === "number") params.amount = formatCompactINR(params.amount, lang);
  if (typeof params.date === "string") params.date = formatShortDate(params.date, lang);
  const n = Number(params.n ?? 0);
  params.promises = lang === "hi" ? (n === 1 ? "वादा टूटा" : "वादे टूटे") : n === 1 ? "promise" : "promises";
  params.times = n === 1 ? "time" : "times";
  params.dayWord = Number(params.dpd) === 1 ? "day" : "days";
  params.daysWord = Number(params.days) === 1 ? "day" : "days";
  return entry[lang].replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));
}

